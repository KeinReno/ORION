import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
const out = process.env.ANDROID_SMOKE_OUTPUT || "../../outputs/android-alpha13/preview";
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 412, height: 915 }, colorScheme: "dark" });
  await context.addInitScript(() => {
    const put = IDBObjectStore.prototype.put;
    IDBObjectStore.prototype.put = function (...args) { if (window.__failSettingWrite) throw new Error("synthetic disk full"); return put.apply(this, args); };
  });
  const page = await context.newPage(); const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("http://127.0.0.1:3180");
  await page.getByRole("heading", { name: "Задачи", exact: true }).waitFor();
  assert.equal(await page.locator(".navigation button").count(), 5);
  assert.equal(await page.locator(".navigation button svg").count(), 5, "all bottom destinations have visible icons");
  await page.getByRole("button", { name: "Ещё", exact: true }).click();
  await page.getByRole("link", { name: /Подключение и синхронизация/ }).waitFor();
  await page.getByRole("button", { name: "Настройки", exact: true }).click();
  await page.getByRole("link", { name: /Внешний вид/ }).waitFor();
  await page.screenshot({ path: out + "/settings-hub-dark.png", fullPage: true });
  await page.getByRole("searchbox", { name: "Найти настройку" }).fill("наклон");
  await page.getByRole("link", { name: /Сила наклона/ }).click();
  await page.waitForURL(/settings\/motion\?field=depth-strength/);
  await page.getByLabel("Сила наклона").waitFor();
  await page.goBack();
  assert.equal(await page.getByRole("searchbox", { name: "Найти настройку" }).inputValue(), "наклон");
  await page.getByRole("searchbox", { name: "Найти настройку" }).fill("");
  await page.getByRole("link", { name: /Внешний вид/ }).click();
  await page.evaluate(() => { window.__failSettingWrite = true; });
  await page.getByLabel("Светлая", { exact: true }).check();
  await page.getByRole("alert").filter({ hasText: "Не удалось сохранить настройку" }).waitFor();
  assert.equal(await page.getByLabel("Светлая", { exact: true }).isChecked(), true, "failed value remains available to retry");
  assert.equal(await page.locator("html").getAttribute("data-theme"), "system", "unsaved theme did not publish to canonical state");
  await page.evaluate(() => { window.__failSettingWrite = false; });
  await page.getByRole("button", { name: "Повторить сохранение", exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === "light");
  await page.getByLabel("Цвета тёмной темы").selectOption("midnight");
  await page.getByText("Сохранено: Цвета тёмной темы", { exact: true }).waitFor();
  await page.reload();
  assert.equal(await page.getByLabel("Светлая", { exact: true }).isChecked(), true);
  assert.equal(await page.getByLabel("Цвета тёмной темы").inputValue(), "midnight");
  await page.getByRole("button", { name: "Настройки", exact: true }).click();
  for (const name of ["Движение и жесты", "Голос и ввод", "Данные и резервные копии", "Обновления", "Диагностика", "О приложении"]) {
    await page.getByRole("link", { name: new RegExp(name) }).click();
    await page.getByRole("button", { name: "Назад к настройкам", exact: true }).click();
    await page.getByRole("searchbox", { name: "Найти настройку" }).waitFor();
  }
  await page.setViewportSize({ width: 320, height: 740 });
  await page.evaluate(() => { document.documentElement.style.fontSize = "200%"; });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "settings hub reflows at 320px / 200% text");
  await page.screenshot({ path: out + "/settings-hub-320-text200.png", fullPage: true });
  await page.goto("http://127.0.0.1:3180/#/scope/" + "a".repeat(64) + "/module/tasks");
  await page.getByRole("heading", { name: "Раздел недоступен", exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "Создать", exact: true }).count(), 0, "mismatched scope cannot create in the wrong workspace");
  await page.getByRole("button", { name: "Задачи", exact: true }).click();
  await page.getByRole("button", { name: "Создать", exact: true }).waitFor();
  await page.getByRole("button", { name: "Создать", exact: true }).click();
  await page.evaluate(() => { window.__failSettingWrite = true; });
  await page.getByLabel("Название", { exact: true }).fill("Черновик при ошибке диска");
  await page.getByRole("alert").filter({ hasText: "Черновик не записан" }).waitFor();
  await page.getByRole("button", { name: "Назад к списку, оставить черновик" }).click();
  await page.waitForTimeout(150);
  assert.equal(await page.getByLabel("Название", { exact: true }).inputValue(), "Черновик при ошибке диска");
  await page.evaluate(() => { window.__failSettingWrite = false; });
  await page.getByRole("button", { name: "Сохранить", exact: true }).click();
  await page.getByRole("heading", { name: "Задачи", exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log("PASS: icon navigation, module catalog, settings search/anchors/Back, independent writes, disk-failure retry, reload, 320px/200%, scope guard; browser only.");
} finally { await browser.close(); }
