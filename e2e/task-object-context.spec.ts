  await expect(detail.getByRole("alert")).toHaveCount(0);
  await page.screenshot({ path: "tmp/redesign/project-task-context-desktop.png" });
  await detail.getByRole("button", { name: "Закрыть", exact: true }).click();
  await expect(inspector).toBeVisible();
  await page.getByRole("button", { name: "Свойства объекта", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Шаг рабочего проекта", exact: true }).first().click();
