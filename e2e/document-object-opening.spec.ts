import { expect, test } from "@playwright/test";
import { apiUrl, disableAllPlugins, register, signIn } from "./support";

test.use({ reducedMotion: "reduce", actionTimeout: 20_000 });

test("standalone document uses office slot, retains failed draft and reloads saved bytes", async ({ page, request }) => {
  test.setTimeout(180_000);
  const account = await register(request, "document-editor");
  const headers = { Authorization: `Bearer ${account.accessToken}` };
  const base = `${apiUrl()}/workspaces/${account.workspaceId}/documents`;
  await request.patch(`${apiUrl()}/settings/preferences`, { headers, data: { theme: "kaiden-precision" } });
  await signIn(page, account); await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto(`/dashboard?workspaceId=${account.workspaceId}`);
  await page.getByRole("button", { name: "Документы", exact: true }).click();
  await page.getByRole("button", { name: "Документ", exact: true }).click();
  await expect.poll(async () => (await (await request.get(base, { headers })).json()).length).toBe(1);
  const [doc] = await (await request.get(base, { headers })).json();
  expect(doc.name).toMatch(/\.docx$/i);
  await page.getByRole("button", { name: `Открытие: ${doc.name}`, exact: true }).click();
  await page.getByRole("menuitem", { name: "Открыть в новой вкладке", exact: true }).click();
  const panel = page.getByRole("region", { name: "Документ", exact: true });
  const editor = panel.locator('.ProseMirror[contenteditable="true"]');
  await expect(editor).toBeVisible();
  const draft = "Текст документа без потерь после переходов";
  await editor.fill(draft);
  await expect(page.getByRole("status", { name: "Сохранение документа", exact: true })).toContainText("Есть несохранённые изменения");
  await page.route(`**/documents/${doc.id}/content`, async route => {
    if (route.request().method() === "POST") await route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ message: "Тестовый сбой записи" }) });
    else await route.continue();
  });
  await panel.getByRole("button", { name: "Сохранить", exact: true }).click();
  await expect(page.getByText("Не удалось сохранить", { exact: true })).toBeVisible();
  await expect(editor).toHaveText(draft);
  await page.clock.install();
  await page.clock.fastForward(11_000);
  await page.route(base, route => route.request().method() === "GET" ? route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ message: "Тестовый сбой метаданных" }) }) : route.continue());
  await page.evaluate(() => { window.dispatchEvent(new Event("offline")); window.dispatchEvent(new Event("online")); });
  await expect(panel.getByRole("alert")).toContainText("Редактор остаётся открыт");
  await expect(editor).toHaveText(draft);
  await page.unroute(base);
  await panel.getByRole("button", { name: "Повторить загрузку сведений", exact: true }).click();
  await expect(panel.getByRole("alert")).toHaveCount(0);
  await expect(editor).toHaveText(draft);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Открыть меню", exact: true }).click();
  await page.getByRole("button", { name: "Задачи", exact: true }).click();
  await expect(page.getByText("Сначала сохраните изменения", { exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(editor).toHaveText(draft);
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.unroute(`**/documents/${doc.id}/content`);
  await panel.getByRole("button", { name: "Сохранить", exact: true }).click();
  await expect(panel.getByText("Всё сохранено", { exact: true })).toBeVisible();
  await expect(page.getByRole("status", { name: "Сохранение документа", exact: true })).toContainText("Всё сохранено");
  await page.reload();
  await expect(editor).toHaveText(draft);
  await panel.getByRole("button", { name: `Открытие: ${doc.name}`, exact: true }).click();
  const popupPromise = page.waitForEvent("popup");
  await page.getByRole("menuitem", { name: "Открыть в отдельном окне", exact: true }).click();
  const popup = await popupPromise;
  await expect(popup.locator('.ProseMirror[contenteditable="true"]')).toHaveText(draft);
  expect(new URL(popup.url()).searchParams.get("workspaceId")).toBe(account.workspaceId);
  expect(new URL(popup.url()).searchParams.get("instance")).toBe(doc.id);
  await popup.close();
  const saved = await (await request.get(base, { headers })).json();
  expect(saved).toHaveLength(1); expect(saved[0].id).toBe(doc.id);
  await page.screenshot({ path: "tmp/redesign/document-office.png" });
});

test("document preview without plugins preserves bytes and denies foreign or deleted file", async ({ page, request, browser }) => {
  test.setTimeout(120_000);
  const account = await register(request, "document-viewer");
  await disableAllPlugins(request, account);
  const headers = { Authorization: `Bearer ${account.accessToken}` };
  const base = `${apiUrl()}/workspaces/${account.workspaceId}/documents`;
  const folderResponse = await request.post(base, { headers, data: { name: "Каталог документов" } });
  expect(folderResponse.ok()).toBe(true);
  const folder = await folderResponse.json();
  const body = "Содержимое файла без изменений";
  const uploaded = await request.post(`${base}/upload`, { headers, multipart: { files: { name: "Материал.txt", mimeType: "text/plain", buffer: Buffer.from(body) } } });
  expect(uploaded.ok(), await uploaded.text()).toBe(true);
  const [doc] = await uploaded.json();
  await request.patch(`${apiUrl()}/settings/preferences`, { headers, data: { theme: "kaiden-precision" } });
  await signIn(page, account); await page.setViewportSize({ width: 1680, height: 1000 });
  await page.goto(`/dashboard?workspaceId=${account.workspaceId}`);
  await page.getByRole("button", { name: "Поиск и команды", exact: true }).click();
  const palette = page.getByRole("dialog", { name: "Поиск и команды", exact: true });
  await palette.getByRole("textbox", { name: "Поиск команд и записей", exact: true }).fill(folder.name);
  await expect(palette.getByRole("button", { name: new RegExp(folder.name) })).toBeVisible();
  await expect(palette.getByRole("button", { name: `Открытие: ${folder.name}`, exact: true })).toHaveCount(0);
  await palette.getByRole("textbox", { name: "Поиск команд и записей", exact: true }).fill(doc.name);
  await palette.getByRole("button", { name: `Открытие: ${doc.name}`, exact: true }).click();
  await palette.getByRole("menuitem", { name: "Открыть рядом", exact: true }).click();
  const panel = page.getByRole("region", { name: "Документ", exact: true });
  await expect(panel.getByText(body, { exact: true })).toBeVisible();
  await page.clock.install();
  await page.clock.fastForward(11_000);
  await page.route(base, route => route.request().method() === "GET" ? route.fulfill({ status: 403, contentType: "application/json", body: JSON.stringify({ message: "Тестовый отказ доступа" }) }) : route.continue());
  await page.evaluate(() => { window.dispatchEvent(new Event("offline")); window.dispatchEvent(new Event("online")); });
  await expect(page.getByText("Не удалось загрузить документ", { exact: true })).toBeVisible();
  await expect(page.getByText(body, { exact: true })).toHaveCount(0);
  await page.unroute(base);
  await page.getByRole("button", { name: "Повторить", exact: true }).click();
  await expect(panel.getByText(body, { exact: true })).toBeVisible();
  const content = await request.get(`${base}/${doc.id}/content`, { headers });
  expect((await content.body()).toString()).toBe(body);
  await page.screenshot({ path: "tmp/redesign/document-viewer.png" });
  const other = await register(request, "document-no-access");
  const context = await browser.newContext(); const denied = await context.newPage();
  await signIn(denied, other);
  await denied.goto(`/panel/document?instance=${doc.id}&workspaceId=${other.workspaceId}`);
  await expect(denied.getByText("Документ недоступен", { exact: true })).toBeVisible();
  await expect(denied.getByText(body, { exact: true })).toHaveCount(0);
  await expect(denied.getByText(doc.name, { exact: true })).toHaveCount(0);
  await context.close();
  const removed = await request.delete(`${base}/${doc.id}`, { headers }); expect(removed.ok()).toBe(true);
  await page.reload();
  await expect(page.getByText("Документ недоступен", { exact: true })).toBeVisible();
  await expect(page.getByText(body, { exact: true })).toHaveCount(0);
});

test("standalone XLSX dispatches to the existing office grid without rewriting bytes", async ({ page, request }) => {
  test.setTimeout(120_000);
  const account = await register(request, "document-sheet");
  const headers = { Authorization: `Bearer ${account.accessToken}` };
  const base = `${apiUrl()}/workspaces/${account.workspaceId}/documents`;
  await signIn(page, account); await page.setViewportSize({ width: 1680, height: 1000 });
  await page.goto(`/dashboard?workspaceId=${account.workspaceId}`);
  await page.getByRole("button", { name: "Документы", exact: true }).click();
  await page.getByRole("button", { name: "Таблица", exact: true }).click();
  await expect.poll(async () => (await (await request.get(base, { headers })).json()).length).toBe(1);
  const [doc] = await (await request.get(base, { headers })).json();
  expect(doc.name).toMatch(/\.xlsx$/i);
  const original = await (await request.get(`${base}/${doc.id}/content`, { headers })).body();
  await page.getByRole("button", { name: `Открытие: ${doc.name}`, exact: true }).click();
  await page.getByRole("menuitem", { name: "Открыть в новой вкладке", exact: true }).click();
  const panel = page.getByRole("region", { name: "Документ", exact: true });
  await expect(panel.getByRole("button", { name: "Вставить диаграмму", exact: true })).toBeVisible();
  await expect(panel.getByRole("table")).toBeVisible();
  const after = await (await request.get(`${base}/${doc.id}/content`, { headers })).body();
  expect(after.equals(original)).toBe(true);
  expect(await (await request.get(base, { headers })).json()).toHaveLength(1);
  await page.screenshot({ path: "tmp/redesign/document-sheet.png" });
});
