import { expect, test } from "@playwright/test";
import { apiUrl, register, signIn } from "./support";

test("publication preview, offline retry, personal copy and revocation", async ({ page, request }) => {
  const owner = await register(request, "publication-owner");
  const headers = { Authorization: `Bearer ${owner.accessToken}` };
  const zoneResponse = await request.post(`${apiUrl()}/workspaces`, { headers, data: { name: "Общая зона теста" } });
  expect(zoneResponse.status()).toBe(201);
  const zone = await zoneResponse.json();
  const taskResponse = await request.post(`${apiUrl()}/workspaces/${owner.workspaceId}/tasks`, { headers, data: { title: "Задача для общей зоны", description: "Проверенный текст [приватный источник](https://private.example/PRIVATE_SECRET)" } });
  const task = await taskResponse.json();
  await signIn(page, owner);
  await page.goto(`/panel/shared?workspaceId=${owner.workspaceId}`);
  await page.getByRole("button", { name: "Поделиться", exact: true }).click();
  await page.getByRole("combobox", { name: "Материал", exact: true }).selectOption(task.id);
  await page.getByLabel("Передать текст", { exact: true }).check();
  await page.getByLabel("Разрешить участникам менять статус оригинальной задачи").check();
  await page.getByRole("button", { name: "Предварительный просмотр" }).click();
  await expect(page.getByText("Участники увидят именно это:")).toBeVisible();
  await expect(page.getByText("PRIVATE_SECRET", { exact: false })).toHaveCount(0);
  await page.getByRole("button", { name: "Опубликовать для участников" }).click();
  const card = page.getByRole("article", { name: "Задача для общей зоны" });
  await expect(card).toBeVisible();
  await page.route("**/publications/*/status", route => route.abort("connectionrefused"));
  await card.getByRole("combobox", { name: "Новый статус", exact: true }).selectOption("in_progress");
  await card.getByRole("button", { name: "Изменить статус" }).click();
  await expect(card.getByRole("button", { name: "Повторить отправку" })).toBeEnabled();
  await page.reload();
  await expect(card.getByRole("button", { name: "Повторить отправку" })).toBeVisible();
  await page.unroute("**/publications/*/status");
  await card.getByRole("button", { name: "Повторить отправку" }).click();
  await expect(card.getByText("Статус: В работе", { exact: true })).toBeVisible();
  await expect(card.getByRole("combobox", { name: "Новый статус", exact: true })).toHaveValue("in_progress");
  await expect(card.getByRole("button", { name: "Повторить отправку" })).toHaveCount(0);
  await card.getByRole("button", { name: "Показывать у меня", exact: true }).click();
  await expect(card.getByText("Публикация добавлена", { exact: false })).toBeVisible();
  await page.getByRole("combobox", { name: "Список", exact: true }).selectOption("pinned");
  await expect(card).toBeVisible();
  await page.getByRole("combobox", { name: "Список", exact: true }).selectOption("zone");
  await card.getByRole("button", { name: "Сделать личную копию" }).click();
  await expect(card.getByText("Личная копия создана.", { exact: false })).toBeVisible();
  await page.screenshot({ path: "test-results/publications-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/publications-narrow.png", fullPage: true });
  await card.getByRole("button", { name: "Отозвать доступ", exact: true }).click();
  await card.getByRole("button", { name: "Отозвать для всех" }).click();
  await expect(card).toHaveCount(0);
  const publications = await request.get(`${apiUrl()}/publications?workspaceId=${zone.id}`, { headers });
  expect(await publications.json()).toEqual([]);
});
