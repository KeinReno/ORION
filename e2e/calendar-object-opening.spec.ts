import { expect, test } from "@playwright/test";
import { apiUrl, disableAllPlugins, register, signIn } from "./support";

test.use({ reducedMotion: "reduce", actionTimeout: 15_000 });
for (const pluginsOff of [false, true]) {
  test(`calendar agenda opens original objects and retains its state (${pluginsOff ? "plugins-off" : "default-full"})`, async ({ page, request }) => {
    test.setTimeout(120_000);
    const account = await register(request, "calendar-objects");
    if (pluginsOff) await disableAllPlugins(request, account);
    const headers = { Authorization: `Bearer ${account.accessToken}` };
    const base = `${apiUrl()}/workspaces/${account.workspaceId}`;
    const post = async (path: string, data: unknown) => {
      const response = await request.post(`${base}/${path}`, { headers, data });
      expect(response.ok(), await response.text()).toBe(true); return response.json();
    };
    const when = new Date(Date.now() + 3_600_000).toISOString();
    const later = new Date(Date.now() + 7_200_000).toISOString();
    const task = await post("tasks", { title: "Календарная задача", status: "todo", dueAt: when });
    const note = await post("notes", { title: "Календарная заметка", body: "Исходный текст", eventAt: later, tags: [] });
    const event = await post("events", { title: "Обычное событие", startAt: when, endAt: later, allDay: false, reminders: [] });
    await request.patch(`${apiUrl()}/settings/preferences`, { headers, data: { theme: "kaiden-precision" } });
    await signIn(page, account); await page.setViewportSize({ width: 1920, height: 1080 });
    await page.goto(`/dashboard?workspaceId=${account.workspaceId}`);
    await page.getByRole("button", { name: "Календарь", exact: true }).click();
    const calendar = page.getByRole("group", { name: "Календарь", exact: true });
    await calendar.getByRole("tab", { name: "Список", exact: true }).click();
    await expect(calendar.getByRole("button", { name: /Обычное событие/ })).toBeVisible();
    await expect(calendar.getByRole("button", { name: "Открытие: Обычное событие", exact: true })).toHaveCount(0);
    const filter = page.getByRole("textbox", { name: "Найти на календаре", exact: true });
    await filter.fill("Календарная");
    await calendar.focus(); await page.keyboard.press("ArrowDown");
    await calendar.getByRole("button", { name: `Открытие: ${task.title}`, exact: true }).click();
    await calendar.getByRole("menuitem", { name: "Открыть рядом", exact: true }).focus();
    await page.keyboard.press("Enter");
    const detail = page.getByRole("region", { name: "Детали задачи", exact: true });
    const title = detail.getByRole("textbox", { name: "Название задачи", exact: true });
    await expect(title).toHaveValue(task.title);
    await expect(calendar).toBeVisible();
    await expect(calendar.getByRole("tab", { name: "Список", exact: true })).toHaveAttribute("aria-selected", "true");
    await expect(filter).toHaveValue("Календарная");
    await page.route(`**/tasks/${task.id}`, async route => {
      if (route.request().method() === "PATCH") await route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ message: "Тестовый сбой" }) });
      else await route.continue();
    });
    await title.fill("Календарная задача — черновик");
    await expect(detail).toContainText("Не удалось сохранить — оставьте задачу открытой");
    await calendar.getByRole("button", { name: `Открытие: ${note.title}`, exact: true }).click();
    const popupPromise = page.waitForEvent("popup");
    await calendar.getByRole("menuitem", { name: "Открыть в отдельном окне", exact: true }).focus();
    await page.keyboard.press("Enter");
    const popup = await popupPromise;
    await expect(popup.getByRole("textbox", { name: "Название заметки", exact: true })).toHaveValue(note.title);
    expect(new URL(popup.url()).searchParams.get("workspaceId")).toBe(account.workspaceId);
    expect(new URL(popup.url()).searchParams.get("instance")).toBe(note.id);
    await popup.close();
    await expect(title).toHaveCount(1);
    await expect(title).toHaveValue("Календарная задача — черновик");
    await calendar.getByRole("button", { name: `Открытие: ${note.title}`, exact: true }).click();
    await calendar.getByRole("menuitem", { name: "Открыть в новой вкладке", exact: true }).click();
    await expect(page.getByRole("textbox", { name: "Название заметки", exact: true })).toHaveValue(note.title);
    await page.getByRole("button", { name: "Календарь", exact: true }).click();
    await expect(calendar.getByRole("tab", { name: "Список", exact: true })).toHaveAttribute("aria-selected", "true");
    await expect(filter).toHaveValue("Календарная");
    await page.unroute(`**/tasks/${task.id}`);
    await detail.getByRole("button", { name: "Повторить", exact: true }).click();
    await expect(detail).toContainText("Всё сохранено");
    const savedTasks = await (await request.get(`${base}/tasks`, { headers })).json();
    const savedNotes = await (await request.get(`${base}/notes`, { headers })).json();
    expect(savedTasks).toHaveLength(1); expect(savedTasks[0].id).toBe(task.id); expect(savedTasks[0].dueAt).toBe(when);
    expect(savedNotes).toHaveLength(1); expect(savedNotes[0].id).toBe(note.id); expect(savedNotes[0].eventAt).toBe(later);
    const from = new Date(Date.now() - 86_400_000).toISOString(); const to = new Date(Date.now() + 3 * 86_400_000).toISOString();
    const events = await (await request.get(`${base}/events?from=${encodeURIComponent(from)}&to=${encodeURIComponent(to)}`, { headers })).json();
    expect(events).toHaveLength(1); expect(events[0].id).toBe(event.id);
    expect(events[0].startAt).toBe(when); expect(events[0].endAt).toBe(later);
    await filter.fill("");
    await calendar.getByRole("button", { name: /Обычное событие/ }).click();
    await expect(page.getByRole("dialog", { name: "Событие", exact: true })).toBeVisible();
    await page.keyboard.press("Escape");
    await expect(page.getByRole("dialog", { name: "Событие", exact: true })).not.toBeVisible();
    await filter.fill("Календарная");
    await page.screenshot({ path: `tmp/redesign/calendar-objects-${pluginsOff ? "plugins-off" : "default-full"}.png` });
  });
}
