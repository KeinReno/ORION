import { expect, test } from "@playwright/test";
import { apiUrl, disableAllPlugins, register, signIn } from "./support";

test.use({ reducedMotion: "reduce" });

test("note context retains Markdown, failed drafts and conflicts across responsive layouts", async ({ page, request }) => {
  test.setTimeout(120_000);
  const account = await register(request, "note-context");
  await disableAllPlugins(request, account);
  const headers = { Authorization: `Bearer ${account.accessToken}` };
  const notesUrl = `${apiUrl()}/workspaces/${account.workspaceId}/notes`;
  const markdown = "# План\n\nТекст **без потерь** и [[Другая заметка]].\n\n- [ ] Проверка\n\n```ts\nconst value = 1;\n```";
  const make = async (title: string) => {
    const response = await request.post(notesUrl, { headers, data: { title, body: markdown, summary: "Описание автора", tags: ["работа"] } });
    expect(response.ok(), await response.text()).toBe(true); return response.json();
  };
  const first = await make("Первая заметка"); await make("Другая заметка");
  await request.patch(`${apiUrl()}/settings/preferences`, { headers, data: { theme: "kaiden-precision" } });
  await signIn(page, account); await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto(`/dashboard?workspaceId=${account.workspaceId}`);
  await page.getByRole("button", { name: "Заметки", exact: true }).click();
  await page.getByRole("button", { name: /Первая заметка/ }).first().click();
  const editor = page.getByRole("form", { name: "Редактор заметки", exact: true });
  const title = editor.getByRole("textbox", { name: "Название заметки", exact: true });
  const toolbar = page.getByRole("banner", { name: "Рабочая область", exact: true });
  await expect(toolbar).toContainText("Первая заметка");
  await page.route(`**/notes/${first.id}`, async route => {
    if (route.request().method() === "PATCH") await route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ message: "Тестовый сбой сохранения" }) });
    else await route.continue();
  });
  await title.fill("Несохранённая заметка");
  await expect(editor).toContainText("Не удалось сохранить — оставьте заметку открытой");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(editor.getByRole("button", { name: "К заметкам", exact: true })).toBeVisible();
  await expect(title).toHaveValue("Несохранённая заметка");
  await expect(page.getByRole("dialog", { name: "Заметка", exact: true })).toHaveCount(0);
  await expect.poll(() => editor.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
  await editor.getByRole("button", { name: "К заметкам", exact: true }).click();
  const discard = page.getByRole("dialog", { name: "Закрыть без сохранения?", exact: true });
  await expect(discard).toBeVisible();
  await discard.getByRole("button", { name: "Отмена", exact: true }).click();
  await page.setViewportSize({ width: 1920, height: 1080 });
  await expect(title).toHaveValue("Несохранённая заметка");
  await page.getByRole("button", { name: "Обзор", exact: true }).click();
  await expect(toolbar).not.toContainText("Несохранённая заметка");
  await page.getByRole("button", { name: "Заметки", exact: true }).click();
  await expect(title).toHaveValue("Несохранённая заметка");
  await page.unroute(`**/notes/${first.id}`);
  await editor.getByRole("button", { name: "Повторить", exact: true }).click();
  await expect(editor).toContainText("Всё сохранено");
  const saved = await (await request.get(`${notesUrl}/${first.id}`, { headers })).json();
  expect(saved).toMatchObject({ title: "Несохранённая заметка", body: markdown, summary: "Описание автора", tags: ["работа"] });
  const remote = await request.patch(`${notesUrl}/${first.id}`, { headers, data: { title: "Версия другого редактора" } });
  expect(remote.ok()).toBe(true);
  await title.fill("Моя версия заметки");
  await expect(editor).toContainText("Эту заметку сохранил кто-то другой");
  await expect(toolbar).toContainText("Конфликт версий");
  await editor.getByRole("button", { name: "Сохранить мою версию поверх", exact: true }).click();
  await expect(editor).toContainText("Всё сохранено");
  await page.screenshot({ path: "tmp/redesign/note-context-desktop.png" });
  await title.fill("");
  await editor.getByRole("button", { name: "Закрыть", exact: true }).click();
  await expect(discard).toBeVisible();
  await discard.getByRole("button", { name: "Отмена", exact: true }).click();
  await title.fill("Моя версия заметки");
  await expect(editor).toContainText("Всё сохранено");
});

test("note inspector stays beside text, adapts without losing fields; compose stays explicitly unsaved", async ({ page, request }) => {
  test.setTimeout(120_000);
  const account = await register(request, "note-inspector");
  const headers = { Authorization: `Bearer ${account.accessToken}` };
  const projectResponse = await request.post(`${apiUrl()}/workspaces/${account.workspaceId}/projects`, { headers, data: { name: "Проект заметки" } });
  expect(projectResponse.ok()).toBe(true); const project = await projectResponse.json();
  await request.patch(`${apiUrl()}/settings/preferences`, { headers, data: { theme: "kaiden-precision" } });
  await signIn(page, account); await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto(`/dashboard?workspaceId=${account.workspaceId}`);
  await page.getByRole("button", { name: "Заметки", exact: true }).click();
  await page.getByRole("button", { name: "Новая", exact: true }).click();
  const editor = page.getByRole("form", { name: "Редактор заметки", exact: true });
  const title = editor.getByRole("textbox", { name: "Название заметки", exact: true });
  await title.fill("Заметка рабочего проекта");
  await expect(page.getByRole("banner", { name: "Рабочая область", exact: true })).toContainText("Новая запись — сохраните явно");
  await editor.getByRole("textbox", { name: "Краткое описание", exact: true }).fill("Создано вручную");
  await editor.getByRole("button", { name: "Свойства, связи и доступ", exact: true }).click();
  const inspector = page.getByRole("complementary", { name: "Свойства заметки", exact: true });
  await expect(inspector).toBeVisible(); await expect(title).toBeVisible();
  const projectPicker = inspector.getByRole("combobox", { name: "Проект", exact: true });
  await projectPicker.click();
  await page.getByRole("option", { name: "Проект заметки", exact: true }).click();
  await page.screenshot({ path: "tmp/redesign/note-inspector-desktop.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(title).toBeHidden();
  await expect(projectPicker).toHaveValue("Проект заметки");
  await expect.poll(() => inspector.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
  await page.screenshot({ path: "tmp/redesign/note-inspector-mobile.png" });
  await inspector.getByRole("button", { name: "Вернуться к тексту заметки", exact: true }).click();
  await expect(title).toHaveValue("Заметка рабочего проекта");
  await expect(editor.getByRole("button", { name: "Свойства, связи и доступ", exact: true })).toBeFocused();
  await page.screenshot({ path: "tmp/redesign/note-context-mobile.png" });
  await editor.getByRole("button", { name: "Создать", exact: true }).first().click();
  await expect(editor).toContainText("Всё сохранено");
  const saved = await (await request.get(`${apiUrl()}/workspaces/${account.workspaceId}/notes`, { headers })).json();
  expect(saved).toHaveLength(1);
  expect(saved[0]).toMatchObject({ title: "Заметка рабочего проекта", summary: "Создано вручную", projectId: project.id });
});
