import { expect, test } from "@playwright/test";
import { apiUrl, disableAllPlugins, register, signIn } from "./support";

test.use({ reducedMotion: "reduce" });

test("saved Precision shell, real project context, pins, inspector, rollback and workspace isolation", async ({ page, request }, testInfo) => {
  const account = await register(request, "precision-shell");
  const headers = { Authorization: `Bearer ${account.accessToken}` };
  const projectResponse = await request.post(`${apiUrl()}/workspaces/${account.workspaceId}/projects`, { headers, data: { name: "Проект первого пространства", description: "Демонстрационный проект оболочки", contextNote: "Сохранённый контекст проекта" } });
  expect(projectResponse.ok(), await projectResponse.text()).toBe(true);
  const project = await projectResponse.json();
  const secondResponse = await request.post(`${apiUrl()}/workspaces`, { headers, data: { name: "Другое пространство" } });
  expect(secondResponse.ok()).toBe(true);
  const second = await secondResponse.json();
  await request.patch(`${apiUrl()}/settings/preferences`, { headers, data: { accent: "blue", backgroundStyle: "grid", surfaceStyle: "glass", sidebarFolders: [{ id: "work", name: "Моя работа", collapsed: true, items: ["tasks", "projects"] }] } });
  await signIn(page, account);
  await page.setViewportSize({ width: 1440, height: 900 });
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/dashboard?workspaceId=${account.workspaceId}`);
  await page.getByRole("textbox", { name: "Быстрый ввод", exact: true }).fill("Черновик переживает смену оформления");
  await page.getByRole("button", { name: "Настройки", exact: true }).click();
  await page.getByRole("button", { name: "Внешний вид", exact: true }).click();
  await page.getByRole("combobox", { name: "Оформление Orion", exact: true }).selectOption("kaiden-precision");
  await expect(page.locator("html")).toHaveAttribute("data-orion-design", "precision");
  await page.locator("summary").filter({ hasText: "Предпросмотр тем" }).click();
  const themePreview = page.getByRole("region", { name: "Предпросмотр тем", exact: true });
  await themePreview.getByRole("combobox", { name: "Палитра образца", exact: true }).selectOption("arctic");
  await themePreview.getByRole("button", { name: "Включить предпросмотр", exact: true }).click();
  await expect(themePreview.getByRole("textbox", { name: "Название образца", exact: true })).toHaveCSS("color", "rgb(23, 33, 43)");
  await themePreview.getByRole("button", { name: "Отменить предпросмотр", exact: true }).click();
  await expect(themePreview.locator('[data-kaiden-theme="kaiden-precision"]')).toHaveCount(1);
  const context = page.getByRole("complementary", { name: "Контекст пространства", exact: true });
  await expect(context.getByRole("button", { name: "Проект первого пространства", exact: true })).toBeVisible();
  // A saved collapsed folder must not swallow module icons in the global rail.
  const modules = page.getByRole("navigation", { name: "Разделы", exact: true });
  await expect(modules.getByRole("button", { name: "Задачи", exact: true })).toBeVisible();
  await modules.getByRole("button", { name: "Дашборд", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Быстрый ввод", exact: true })).toHaveValue("Черновик переживает смену оформления");
  await context.getByRole("button", { name: "Проект первого пространства", exact: true }).click();
  await page.getByRole("button", { name: "Свойства объекта", exact: true }).click();
  const inspector = page.getByRole("complementary", { name: "Свойства проекта", exact: true });
  await expect(inspector.getByText("Сохранённый контекст проекта", { exact: true })).toBeVisible();
  await expect(inspector.getByRole("button", { name: "Материалы", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { level: 1, name: "Проект первого пространства", exact: true })).toBeVisible();
  await context.getByRole("button", { name: "Действия проекта Проект первого пространства", exact: true }).click();
  await page.getByRole("menuitem", { name: "Закрепить проект", exact: true }).click();
  await expect(page.getByRole("menu")).toHaveCount(0);
  expect(await context.locator(".orion-scroll").evaluate(node => node.scrollLeft === 0 && node.scrollWidth <= node.clientWidth)).toBe(true);
  await expect(context.getByRole("region", { name: "Закреплённые проекты", exact: true }).getByRole("button", { name: "Проект первого пространства", exact: true })).toBeVisible();
  await testInfo.attach("precision-desktop.png", { body: await page.screenshot({ path: "tmp/redesign/precision-shell-desktop.png" }), contentType: "image/png" });
  await context.getByRole("button", { name: "Действия проекта Проект первого пространства", exact: true }).click();
  const opening = page.waitForEvent("popup");
  await page.getByRole("menuitem", { name: "Открыть в отдельном окне", exact: true }).click();
  const detached = await opening;
  await expect(detached.locator("html")).toHaveAttribute("data-orion-design", "precision");
  await expect(detached.getByRole("heading", { name: "Проект первого пространства", exact: true })).toBeVisible();
  expect(new URL(detached.url()).searchParams.get("workspaceId")).toBe(account.workspaceId);
  await page.reload();
  await expect(page.locator("html")).toHaveAttribute("data-orion-design", "precision");
  await expect(context.getByRole("region", { name: "Закреплённые проекты", exact: true }).getByRole("button", { name: "Проект первого пространства", exact: true })).toBeVisible();
  await context.getByRole("button", { name: /Пространство:/ }).click();
  await page.getByRole("textbox", { name: "Найти пространство", exact: true }).fill("Другое");
  await page.getByRole("option", { name: /Другое пространство/ }).click();
  await expect(context.getByText("Проектов пока нет.", { exact: false })).toBeVisible();
  await expect(context.getByText("Проект первого пространства", { exact: true })).toHaveCount(0);
  await expect(page.getByRole("complementary", { name: "Свойства проекта", exact: true })).toHaveCount(0);
  await context.getByRole("button", { name: /Пространство:/ }).click();
  await page.getByRole("textbox", { name: "Найти пространство", exact: true }).fill("precision-shell");
  await page.getByRole("option", { name: /precision-shell/ }).click();
  await expect(context.getByRole("region", { name: "Закреплённые проекты", exact: true }).getByRole("button", { name: "Проект первого пространства", exact: true })).toBeVisible();
  // Roll back through the same saved preference; other personal choices are retained.
  await page.getByRole("button", { name: "Настройки", exact: true }).click();
  await page.getByRole("button", { name: "Внешний вид", exact: true }).click();
  await page.getByRole("combobox", { name: "Оформление Orion", exact: true }).selectOption("dark");
  await expect(page.locator("html")).toHaveAttribute("data-orion-design", "legacy");
  await expect(detached.locator("html")).toHaveAttribute("data-orion-design", "legacy");
  await detached.close();
  await expect(context).toHaveCount(0);
  const saved = await (await request.get(`${apiUrl()}/settings/preferences`, { headers })).json();
  expect(saved).toMatchObject({ theme: "dark", accent: "blue", backgroundStyle: "grid", surfaceStyle: "glass" });
  expect(saved.sidebarFolders[0].items).toEqual(["tasks", "projects"]);
  expect(errors).toEqual([]);
  expect(second.id).not.toBe(account.workspaceId); expect(project.workspaceId).toBe(account.workspaceId);
});

test("Precision at 390px with plugins off: context drawer, keyboard search and no document overflow", async ({ page, request }, testInfo) => {
  const account = await register(request, "precision-mobile");
  await disableAllPlugins(request, account);
  const headers = { Authorization: `Bearer ${account.accessToken}` };
  const response = await request.post(`${apiUrl()}/workspaces/${account.workspaceId}/projects`, { headers, data: { name: "Мобильный проект" } });
  expect(response.ok()).toBe(true);
  await request.patch(`${apiUrl()}/settings/preferences`, { headers, data: { theme: "kaiden-precision" } });
  await signIn(page, account); await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`/dashboard?workspaceId=${account.workspaceId}`);
  await page.getByRole("textbox", { name: "Быстрый ввод", exact: true }).fill("Этот черновик нельзя потерять");
  await page.getByRole("button", { name: "Контекст пространства", exact: true }).click();
  const drawer = page.getByRole("dialog", { name: "Навигация пространства", exact: true });
  await expect(drawer.getByRole("button", { name: "Мобильный проект", exact: true })).toBeVisible();
  await drawer.getByRole("button", { name: "Виды проекта Мобильный проект", exact: true }).click();
  await expect(drawer.getByRole("button", { name: "План", exact: true })).toHaveCount(0);
  await expect(drawer.getByRole("button", { name: "Материалы", exact: true })).toBeVisible();
  await drawer.getByRole("button", { name: "Мобильный проект", exact: true }).click();
  await expect(drawer).toHaveCount(0);
  await expect(page.getByRole("textbox", { name: "Быстрый ввод", exact: true })).toHaveValue("Этот черновик нельзя потерять");
  await expect(page.getByText("Сначала сохраните изменения", { exact: true })).toBeVisible();
  await page.getByRole("textbox", { name: "Быстрый ввод", exact: true }).fill("");
  await page.getByRole("button", { name: "Контекст пространства", exact: true }).click();
  await drawer.getByRole("button", { name: "Мобильный проект", exact: true }).click();
  await page.getByRole("button", { name: "Свойства объекта", exact: true }).click();
  const projectDialog = page.getByRole("dialog", { name: "Контекст проекта", exact: true });
  await expect(projectDialog).toBeVisible();
  await expect(projectDialog).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(projectDialog).toHaveCount(0);
  await page.getByRole("button", { name: "Поиск и команды", exact: true }).click();
  const palette = page.getByRole("dialog", { name: "Поиск и команды", exact: true });
  await expect(palette).toBeVisible();
  // The search field's autoFocus wins: typing goes straight into it (the dialog no longer pulls focus off it).
  await expect(palette.getByRole("textbox", { name: "Поиск команд и записей", exact: true })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog", { name: "Поиск и команды", exact: true })).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "Мобильный проект", exact: true })).toBeVisible();
  await testInfo.attach("precision-mobile.png", { body: await page.screenshot({ path: "tmp/redesign/precision-shell-mobile.png" }), contentType: "image/png" });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.getByRole("button", { name: "Открыть меню", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 768, height: 900 });
  await expect(page.getByRole("complementary", { name: "Контекст пространства", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Мобильный проект", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "tmp/redesign/precision-shell-tablet.png" });
});
