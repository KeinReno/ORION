/**
 * Необязательный токен чтения релизов из локального окружения. Он не
 * включается в репозиторий или установщик; основной путь для пользователя —
 * один раз сохранить свой токен в зашифрованных настройках приложения.
 */
export function builtinGithubUpdateToken(): string {
  return (process.env.ORION_GITHUB_UPDATE_TOKEN ?? "").trim();
}
