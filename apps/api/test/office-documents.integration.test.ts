import type { INestApplication } from "@nestjs/common";
import { NestFactory } from "@nestjs/core";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { AppModule } from "../src/app.module";
import { PrismaService } from "../src/common/prisma.service";
import { configureApp } from "../src/configure-app";
// O02 — cross-app import by design: this test proves the O01/O01b codec
// layer (apps/web/plugins/documents-office/codecs/*) actually round-trips through the REAL
// DocumentsService/upload/content HTTP path, not just in isolation (as O01's
// own unit tests already proved). The codec has no server-side counterpart —
// per 21-OFFICE-IMPLEMENTATION.md, office documents stay a plain
// Document/DocumentVersion, and parsing/serializing DOCX/XLSX is entirely a
// client concern — so exercising it against the API necessarily means
// importing the client codec into an API-side test. Node module resolution
// for these files walks up from their own location (apps/web/node_modules),
// so this works under the root vitest.integration.config.mts without any
// package/workspace changes.
//
// This file is excluded from `apps/api/tsconfig.test.json` (see that file):
// apps/web's TS project uses a different module/moduleResolution setup
// (needed for `modern-xlsx`'s ESM-only types and `import.meta`) than
// apps/api's CommonJS/node10 project, and apps/api's `rootDir` legitimately
// rejects a source file living outside it. Unifying the two tsconfigs just
// for one cross-app test file was not worth the coupling — vitest already
// transpiles this file per-file (no project-wide type check), and the
// runtime behavior proven by actually running it is the point of this file,
// not its own type-soundness.
import { tiptapJsonToDocx, docxToTiptapJson } from "../../web/plugins/documents-office/codecs/docx-codec";
import { workbookStateToXlsx, xlsxToWorkbookState, recalculate, type WorkbookState } from "../../web/plugins/documents-office/codecs/xlsx-codec";

const DOCX_MIME = "application/vnd.openxmlformats-officedocument.wordprocessingml.document";
const XLSX_MIME = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";

/**
 * O02 — model of how the editor's in-memory content becomes DOCX/XLSX bytes
 * and back, proven against the real save/open path, plus the conflict-policy
 * and invalid-file decisions the plan asked O02 to make explicit. See the
 * O02 entry in 12-PROGRESS.md for the write-up; this file is the evidence.
 *
 * Decisions this test locks in (see 12-PROGRESS.md "O02" for the full
 * reasoning):
 *  - No new server contract: open = the existing `GET .../documents/:id/content`
 *    (raw bytes), save = the existing `POST .../documents/:id/content`
 *    (`DocumentsService.replaceContent`), create = the existing
 *    `POST .../documents/upload` with client-generated bytes. All parsing/
 *    serialization is client-side (apps/web/plugins/documents-office/codecs/*), proven here by
 *    actually calling it, not asserting compatibility on paper.
 *  - No CAS for Document/DocumentVersion: `replaceContent` has no
 *    `expectedRevision`-style parameter today (unlike `Note.revision`), and
 *    O02 does NOT add one specifically for office files — that would special-
 *    case one Document mimeType out of the last-write-wins semantics every
 *    other Document type already has, which is the inconsistency
 *    CLAUDE.md's module contract explicitly warns against. Confirmed below:
 *    a second replaceContent from a "different client" succeeds and simply
 *    becomes the new current version; the first save is never lost — it is
 *    preserved as a DocumentVersion, exactly like it would be for a .txt or
 *    .pdf overwrite.
 *  - No server-side DOCX/XLSX validation: `DocumentsService` stores whatever
 *    bytes arrive under the client-declared mimeType, office or not — proven
 *    below by uploading a garbage buffer under the DOCX mimeType, which the
 *    API accepts (200/201) exactly like any other file, and only the
 *    client-side codec rejects it when it later tries to parse it.
 */
describe("Office documents (O02) — DOCX/XLSX codec round-trips through the real upload/content path", () => {
  let app: INestApplication;
  let prisma: PrismaService;
  let baseUrl: string;
  const runId = `${Date.now()}-${Math.random().toString(36).slice(2)}`;
  const emailPrefix = `office-docs-${runId}`;

  beforeAll(async () => {
    app = await NestFactory.create(AppModule, { logger: false });
    configureApp(app);
    await app.listen(0, "127.0.0.1");
    const address = app.getHttpServer().address() as { port: number };
    baseUrl = `http://127.0.0.1:${address.port}`;
    prisma = app.get(PrismaService);
  });

  afterAll(async () => {
    if (prisma) {
      await prisma.asSystem(async (tx) => {
        const users = await tx.user.findMany({ where: { email: { startsWith: emailPrefix } }, select: { id: true } });
        if (users.length === 0) return;
        const userIds = users.map((u) => u.id);
        const memberships = await tx.workspaceMember.findMany({ where: { userId: { in: userIds } }, select: { workspaceId: true } });
        const workspaceIds = [...new Set(memberships.map((m) => m.workspaceId))];
        await tx.user.deleteMany({ where: { id: { in: userIds } } });
        await tx.workspace.deleteMany({ where: { id: { in: workspaceIds } } });
        const leftovers = await tx.workspace.count({ where: { id: { in: workspaceIds } } });
        if (leftovers > 0) throw new Error(`Cleanup left ${leftovers} test workspace(s) behind`);
      });
    }
    await app?.close();
  });

  async function register(name: string) {
    const response = await fetch(`${baseUrl}/auth/register`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ email: `${emailPrefix}-${name}@example.test`, password: "integration-password-123", name })
    });
    expect(response.status).toBe(201);
    const body = (await response.json()) as { accessToken: string; user: { id: string } };
    const wsRes = await fetch(`${baseUrl}/workspaces/me`, { headers: { Authorization: `Bearer ${body.accessToken}` } });
    const workspaces = (await wsRes.json()) as Array<{ id: string }>;
    return { ...body, workspaceId: workspaces[0].id };
  }

  async function uploadBytes(workspaceId: string, token: string, name: string, mime: string, bytes: Buffer) {
    const form = new FormData();
    form.append("files", new Blob([bytes], { type: mime }), name);
    const response = await fetch(`${baseUrl}/workspaces/${workspaceId}/documents/upload`, {
      method: "POST",
      headers: { Authorization: `Bearer ${token}` },
      body: form
    });
    const data = (await response.json()) as Array<{ id: string; name: string; mimeType: string | null }>;
    return { status: response.status, doc: data?.[0] };
  }

  async function replaceContent(workspaceId: string, token: string, id: string, name: string, mime: string, bytes: Buffer) {
    const form = new FormData();
    form.append("file", new Blob([bytes], { type: mime }), name);
    return fetch(`${baseUrl}/workspaces/${workspaceId}/documents/${id}/content`, {
      method: "POST",
      headers: { Authorization: `Bearer ${token}` },
      body: form
    });
  }

  async function downloadBytes(workspaceId: string, token: string, id: string) {
    const response = await fetch(`${baseUrl}/workspaces/${workspaceId}/documents/${id}/content`, {
      headers: { Authorization: `Bearer ${token}` }
    });
    expect(response.status).toBe(200);
    return Buffer.from(await response.arrayBuffer());
  }

  it("DOCX: client-generated document, saved, downloaded and re-edited through the real API — no content lost", async () => {
    const user = await register("docx");

    // "Create document" (O02 point 4): generate a valid DOCX from a Tiptap
    // JSON model client-side, upload it as an ordinary file — no new
    // create-office endpoint.
    const draftV1 = {
      type: "doc",
      content: [
        { type: "heading", attrs: { level: 1 }, content: [{ type: "text", text: "Отчёт по проекту" }] },
        { type: "paragraph", content: [{ type: "text", text: "Первая версия текста.", marks: [{ type: "bold" }] }] }
      ]
    };
    const v1Bytes = await tiptapJsonToDocx(draftV1);
    const uploaded = await uploadBytes(user.workspaceId, user.accessToken, "report.docx", DOCX_MIME, v1Bytes);
    expect(uploaded.status).toBe(201);
    expect(uploaded.doc.mimeType).toBe(DOCX_MIME);

    // "Open" (O02 point 2): plain GET .../content, then parse client-side.
    const downloadedV1 = await downloadBytes(user.workspaceId, user.accessToken, uploaded.doc.id);
    const parsedV1 = await docxToTiptapJson(downloadedV1);
    const textV1 = JSON.stringify(parsedV1);
    expect(textV1).toContain("Отчёт по проекту");
    expect(textV1).toContain("Первая версия текста.");

    // "Edit" purely in memory, then "Save" (O02 point 3): serialize and
    // upload as a normal replaceContent — a new DocumentVersion.
    const draftV2 = {
      type: "doc",
      content: [
        { type: "heading", attrs: { level: 1 }, content: [{ type: "text", text: "Отчёт по проекту" }] },
        { type: "paragraph", content: [{ type: "text", text: "Вторая версия текста, отредактированная в ORION." }] }
      ]
    };
    const v2Bytes = await tiptapJsonToDocx(draftV2);
    const saved = await replaceContent(user.workspaceId, user.accessToken, uploaded.doc.id, "report.docx", DOCX_MIME, v2Bytes);
    expect(saved.status).toBeLessThan(300);

    const downloadedV2 = await downloadBytes(user.workspaceId, user.accessToken, uploaded.doc.id);
    const parsedV2 = await docxToTiptapJson(downloadedV2);
    const textV2 = JSON.stringify(parsedV2);
    expect(textV2).toContain("Вторая версия текста, отредактированная в ORION.");

    // History (O02: no new content model — plain DocumentVersion). The
    // archived version still parses back to the ORIGINAL text.
    const versionsRes = await fetch(`${baseUrl}/workspaces/${user.workspaceId}/documents/${uploaded.doc.id}/versions`, {
      headers: { Authorization: `Bearer ${user.accessToken}` }
    });
    const versions = (await versionsRes.json()) as Array<{ id: string; versionNumber: number }>;
    expect(versions.length).toBe(1);
    const versionContentRes = await fetch(
      `${baseUrl}/workspaces/${user.workspaceId}/documents/${uploaded.doc.id}/versions/${versions[0].id}/content`,
      { headers: { Authorization: `Bearer ${user.accessToken}` } }
    );
    expect(versionContentRes.status).toBe(200);
    const archivedBytes = Buffer.from(await versionContentRes.arrayBuffer());
    const archivedParsed = await docxToTiptapJson(archivedBytes);
    expect(JSON.stringify(archivedParsed)).toContain("Первая версия текста.");
  });

  it("XLSX: workbook with cross-sheet formulas round-trips through upload/content and still recalculates correctly", async () => {
    const user = await register("xlsx");

    const state: WorkbookState = {
      sheets: [
        { name: "Данные", rows: [[{ value: 10 }], [{ value: 20 }], [{ value: null, formula: "SUM(A1:A2)" }]] },
        { name: "Итоги", rows: [[{ value: null, formula: "Данные!A3*2" }]] }
      ]
    };
    const recalculated = recalculate(state);
    const bytes = await workbookStateToXlsx(recalculated);

    const uploaded = await uploadBytes(user.workspaceId, user.accessToken, "budget.xlsx", XLSX_MIME, bytes);
    expect(uploaded.status).toBe(201);
    expect(uploaded.doc.mimeType).toBe(XLSX_MIME);

    const downloaded = await downloadBytes(user.workspaceId, user.accessToken, uploaded.doc.id);
    const parsed = await xlsxToWorkbookState(downloaded);
    const reRecalculated = recalculate(parsed);

    const dataSheet = reRecalculated.sheets.find((s) => s.name === "Данные")!;
    const summarySheet = reRecalculated.sheets.find((s) => s.name === "Итоги")!;
    expect(dataSheet.rows[2][0].value).toBe(30);
    expect(summarySheet.rows[0][0].value).toBe(60);

    // Edit a cell ("open" -> in-memory edit -> "save"), confirm formulas
    // recompute downstream and the saved file (a new DocumentVersion) is
    // what a subsequent open sees.
    const editedRows = parsed.sheets.map((s) =>
      s.name === "Данные" ? { ...s, rows: s.rows.map((row, i) => (i === 0 ? [{ value: 100 }] : row)) } : s
    );
    const edited = recalculate({ sheets: editedRows });
    const v2Bytes = await workbookStateToXlsx(edited);
    const saved = await replaceContent(user.workspaceId, user.accessToken, uploaded.doc.id, "budget.xlsx", XLSX_MIME, v2Bytes);
    expect(saved.status).toBeLessThan(300);

    const downloadedV2 = await downloadBytes(user.workspaceId, user.accessToken, uploaded.doc.id);
    const parsedV2 = recalculate(await xlsxToWorkbookState(downloadedV2));
    const dataV2 = parsedV2.sheets.find((s) => s.name === "Данные")!;
    const summaryV2 = parsedV2.sheets.find((s) => s.name === "Итоги")!;
    expect(dataV2.rows[2][0].value).toBe(120);
    expect(summaryV2.rows[0][0].value).toBe(240);
  });

  it("save conflict policy (O02 point 5): sequential replaceContent calls are last-write-wins, no expectedRevision required, nothing is silently lost", async () => {
    const user = await register("conflict");
    const v1 = await tiptapJsonToDocx({ type: "doc", content: [{ type: "paragraph", content: [{ type: "text", text: "A" }] }] });
    const uploaded = await uploadBytes(user.workspaceId, user.accessToken, "seq.docx", DOCX_MIME, v1);

    // "Client 1" opens (implicitly — it already has the content), saves.
    const clientOneEdit = await tiptapJsonToDocx({
      type: "doc",
      content: [{ type: "paragraph", content: [{ type: "text", text: "Edited by client 1" }] }]
    });
    const saveOne = await replaceContent(user.workspaceId, user.accessToken, uploaded.doc.id, "seq.docx", DOCX_MIME, clientOneEdit);
    expect(saveOne.status).toBeLessThan(300);

    // "Client 2" opens what is now current (client 1's save), edits, saves —
    // the API accepts it with no revision token at all (confirming
    // replaceContent has no CAS today, unlike Note.revision).
    const currentAfterOne = await downloadBytes(user.workspaceId, user.accessToken, uploaded.doc.id);
    const currentParsed = await docxToTiptapJson(currentAfterOne);
    expect(JSON.stringify(currentParsed)).toContain("Edited by client 1");

    const clientTwoEdit = await tiptapJsonToDocx({
      type: "doc",
      content: [{ type: "paragraph", content: [{ type: "text", text: "Edited by client 2" }] }]
    });
    const saveTwo = await replaceContent(user.workspaceId, user.accessToken, uploaded.doc.id, "seq.docx", DOCX_MIME, clientTwoEdit);
    expect(saveTwo.status).toBeLessThan(300);

    const final = await docxToTiptapJson(await downloadBytes(user.workspaceId, user.accessToken, uploaded.doc.id));
    expect(JSON.stringify(final)).toContain("Edited by client 2");

    // Client 1's save is not lost — it is the archived DocumentVersion.
    const versionsRes = await fetch(`${baseUrl}/workspaces/${user.workspaceId}/documents/${uploaded.doc.id}/versions`, {
      headers: { Authorization: `Bearer ${user.accessToken}` }
    });
    const versions = (await versionsRes.json()) as Array<{ id: string }>;
    expect(versions.length).toBe(2);
  });

  it("invalid file bytes (O02 point 6): the API stores/serves them like any file; only the CLIENT codec rejects them", async () => {
    const user = await register("invalid");
    const garbage = Buffer.from("this is not a valid docx zip archive at all");

    // Server has no idea this is supposed to be a DOCX — it is documents'
    // "binary storage, server does not parse the format" invariant, proven
    // by the upload succeeding exactly like a real DOCX would.
    const uploaded = await uploadBytes(user.workspaceId, user.accessToken, "broken.docx", DOCX_MIME, garbage);
    expect(uploaded.status).toBe(201);
    expect(uploaded.doc.mimeType).toBe(DOCX_MIME);

    const downloaded = await downloadBytes(user.workspaceId, user.accessToken, uploaded.doc.id);
    expect(downloaded.equals(garbage)).toBe(true);

    // The client-side codec is where "can't open this" is decided — it
    // throws, which O03/O04's UI is expected to catch and degrade to
    // preview/download instead of crashing the editor tab.
    await expect(docxToTiptapJson(downloaded)).rejects.toThrow();
  });
});
