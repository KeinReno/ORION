// Вид свечей на графике. Данные для расчётов (сигналы, бэктест, средние) не меняются — только отрисовка.

import type { Candle } from "./types";

/** Таймфреймы, где на тонком рынке свечи рассыпаются в чёрточки с разрывами. */
export const JOINABLE_TFS = new Set(["1m", "5m", "10m", "15m"]);

/**
 * Свечи «без разрывов»: открытие каждой свечи рисуется от закрытия предыдущей.
 * Биржа открывает минутную свечу ценой первой сделки, и при редких сделках соседние свечи не стыкуются;
 * так же рисуют внутридневные графики многие терминалы. Закрытия, максимумы и минимумы остаются настоящими,
 * тело свечи показывает движение от прошлого закрытия к этому.
 */
export function joinCandles(candles: Candle[]): Candle[] {
  return candles.map((c, i) => {
    if (i === 0) return c;
    const o = candles[i - 1].c;
    return o === c.o ? c : { ...c, o, h: Math.max(c.h, o), l: Math.min(c.l, o) };
  });
}
