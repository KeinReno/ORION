def forecast_facts(f) -> str:
    """Только поля снимка. Скрытую вероятность в текст не кладём, чтобы модель не выдала её за факт."""
    cal = f.calibration or {}
    term = (f.distribution or {}).get("terminal") or {}
    show = term.get("prob_up_status") == "calibrated"
    lines = [
        f"инструмент: {f.symbol}, таймфрейм {f.tf}, рынок {f.market}",
        f"горизонт, свечей: {f.horizon}",
        f"цена основания: {f.base_price}",
        f"режим: направление {f.regime.get('trend')}, волатильность {f.regime.get('volatility')}, шок {f.regime.get('shock')}",
        f"аналогов выбрано: {f.analogues.get('chosen')} из {f.analogues.get('candidates')}",
        f"отбор по режиму: {f.analogues.get('regime_filtered')}",
        f"калибровка: состояние {cal.get('state')}, вердикт {cal.get('verdict')}",
        f"заметка калибровки: {cal.get('note')}",
        f"вероятность роста: {term.get('prob_up_pct') if show else 'скрыта'} (статус {term.get('prob_up_status')})",
        f"медианная просадка пути, %: {f.distribution.get('mae_median_pct')}",
        f"медианный ход в плюс, %: {f.distribution.get('mfe_median_pct')}",
    ]
    for s in f.scenarios or []:
        prob = s.get("probability")
        lines.append(
            f"сценарий {s.get('id')} ({s.get('label')}): медиана к горизонту {s.get('terminal_median_pct')}%, "
            f"доля путей {prob if prob is not None else 'скрыта'}, отмена: {(s.get('invalidation') or {}).get('text')}"
        )
    barriers = (f.distribution or {}).get("barriers")
    if barriers:
        lines.append(
            "барьеры: цель раньше стопа "
            f"{barriers.get('target_before_stop_pct') if barriers.get('status') == 'calibrated' else 'скрыто'}, "
            f"стоп раньше цели {barriers.get('stop_before_target_pct') if barriers.get('status') == 'calibrated' else 'скрыто'}"
        )
    if f.warnings:
        lines.append("предупреждения: " + " | ".join(f.warnings))
    return "\n".join(lines)


